USE SCHEMA AIRLINE_DWH.MARTS;
CREATE OR REPLACE SECURE VIEW FACT_FLIGHTS_SECURE AS
SELECT 
    f.*, 
    a.COUNTRY_NAME
FROM AIRLINE_DWH.CORE.FLIGHTS f
JOIN AIRLINE_DWH.CORE.AIRPORTS a ON f.AIRPORT_ID = a.AIRPORT_ID
WHERE a.COUNTRY_NAME IN (
    SELECT ALLOWED_COUNTRY 
    FROM AIRLINE_DWH.CORE.SECURITY_MAPPING 
    WHERE ROLE_NAME = CURRENT_ROLE()
);

